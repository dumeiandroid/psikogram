  /**
   * Konversi usia (angka) ke key string yang dipakai pada tabel NORMA.
   */
  function getUsiaKey(usia) {
    if (usia >= 51) return '51-60';
    if (usia >= 46) return '46-50';
    if (usia >= 41) return '41-45';
    if (usia >= 36) return '36-40';
    if (usia >= 31) return '31-35';
    if (usia >= 26) return '26-30';
    if (usia >= 21) return '21-25';
    if (usia >= 19) return '19-20';
    if (usia === 18) return '18';
    if (usia === 17) return '17';
    if (usia === 16) return '16';
    if (usia === 15) return '15';
    if (usia === 14) return '14';
    if (usia === 13) return '13';
    return '12'; // ≤ 12
  }

  /**
   * Ambil nilai SW dari tabel norma.
   * @param {string} subtes  - Nama subtes: 'SE','WA','AN','GE','ME','RA','ZR','FA','WU'
   * @param {number} rw      - Nilai RW (mentah)
   * @param {string} usiaKey - Key usia hasil getUsiaKey()
   * @returns {number|''} Nilai SW, atau '' jika tidak ditemukan
   */
  function getSW(subtes, rw, usiaKey) {
    const norma = NORMA[usiaKey];
    if (!norma) return '';
    const tabel = norma[subtes];
    if (!tabel) return '';
    for (let i = 0; i < tabel.length; i++) {
      if (rw >= tabel[i][0]) return tabel[i][1];
    }
    return '';
  }

  /**
   * Ambil nilai SW Gesamt (dari total RW semua subtes).
   * @param {number} jml     - Total RW semua subtes
   * @param {string} usiaKey - Key usia hasil getUsiaKey()
   * @returns {number|''} Nilai SW Gesamt, atau '' jika tidak ditemukan
   */
  function getGesamtSW(jml, usiaKey) {
    const norma = NORMA[usiaKey];
    if (!norma || !norma.GESAMT) return '';
    for (const row of norma.GESAMT) {
      if (jml >= row[0] && jml <= row[1]) return row[2];
    }
    return norma.GESAMT[norma.GESAMT.length - 1][2];
  }

  /**
   * Konversi total SW Gesamt → IQ.
   * @param {number} swTotal - Total SW Gesamt
   * @returns {number} Nilai IQ
   */
  function getIQ(swTotal) {
    for (let i = 0; i < IQ_NORM.length; i++) {
      if (swTotal >= IQ_NORM[i][0]) return IQ_NORM[i][1];
    }
    return IQ_NORM[IQ_NORM.length - 1][1];
  }

  /**
   * Hitung semua nilai SW dan IQ dari skor RW IST.
   * @param {Object} rwScores - { SE, WA, AN, GE, ME, RA, ZR, FA, WU, _GE_raw }
   * @param {number} usia     - Usia peserta (angka)
   * @returns {Object} { usiaKey, swPerSubtes, jml, gesamtSW, iq }
   */
  function hitungIST(rwScores, usia) {
    const usiaKey = getUsiaKey(usia || 0);
    const keys = ['SE','WA','AN','GE','ME','RA','ZR','FA','WU'];
    let jml = 0;
    const swPerSubtes = {};

    keys.forEach(k => {
      const rw = rwScores[k] !== undefined ? rwScores[k] : 0;
      jml += rw;
      swPerSubtes[k] = getSW(k, rw, usiaKey);
    });

    const gesamtSW = getGesamtSW(jml, usiaKey);
    const iq = gesamtSW !== '' ? getIQ(parseInt(gesamtSW)) : '';

    return { usiaKey, swPerSubtes, jml, gesamtSW, iq };
  }

